//! The `ds doc` subcommand: the deterministic surface dumper. Bare `ds
//! doc` renders the toolchain's own reference — the language's ambient
//! core and the `@std` package's own declarations, every `pub` face and
//! every impl with its `///` doc run rendered — `ds doc TARGET` renders
//! one .ds file or package root the same way, and `ds doc --errors`
//! renders the error-code table straight off the diagnostic
//! registry. The output is sorted, timestamp-free, and newline-stable, so
//! the checked-in documents (`docs/en/reference.md`, `docs/en/errors.md`)
//! are the dumper's own bytes and the drift tests fail when the surface
//! or the registry moves without regenerating them.

use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result, bail};
use clap::Args;
use ds_diag::{ErrorClass, ErrorCode, Files};
use ds_parse::{Ast, Expr, ItemKind, Pattern, Trivia, Vis};

/// The `ds doc` surface: an optional target, an `--errors` switch.
#[derive(Debug, Args)]
pub struct DocArgs {
    /// Render the error-code table instead of a surface
    #[arg(long)]
    errors: bool,
    /// A .ds file or a package root; without it the toolchain's own
    /// language and @std surface renders
    target: Option<PathBuf>,
}

/// The checked-in language and @std reference's header. No timestamps, no
/// version: the file is the dumper's own bytes on every regeneration.
const REFERENCE_HEADER: &str = concat!(
    "# DreamScript language and @std reference\n",
    "\n",
    "Generated by `ds doc` from the toolchain's own sources; do not edit by hand. ",
    "Declarations render sorted per family, each with its `///` doc run rendered; ",
    "regenerate after a surface change with `ds doc > docs/en/reference.md`.\n",
);

/// The checked-in error table's header, same stability contract.
const ERRORS_HEADER: &str = concat!(
    "# DreamScript error codes\n",
    "\n",
    "Generated by `ds doc --errors` from the diagnostic registry; do not edit by hand. ",
    "A code's meaning is pinned at its registry entry, so the table regenerates ",
    "whenever the registry moves.\n",
);

/// Renders the requested document to stdout.
///
/// # Errors
///
/// An unreadable target, a member that fails to parse, and a root holding
/// no .ds source.
pub fn doc(args: &DocArgs) -> Result<()> {
    let text = if args.errors {
        errors_reference()
    } else {
        match &args.target {
            Some(target) => target_reference(target)?,
            None => toolchain_reference()?,
        }
    };
    print!("{text}");
    Ok(())
}

/// One rendered declaration: its family, its heading label, the `///`
/// doc run attached to it, and its signature face.
struct Entry {
    family: Family,
    label: Option<String>,
    doc: Vec<String>,
    face: String,
}

/// The surface families, in the reference's fixed section order (the
/// derive order is the sort order).
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Family {
    /// Traits and their member signatures.
    Trait,
    /// Structs with their fields (deinits stay out, like every body).
    Struct,
    /// Enums with their cases.
    Enum,
    /// Unit and payload tags.
    Tag,
    /// `type` aliases.
    Alias,
    /// Signatures and externs; a bodied fn renders through its converted
    /// binding's lambda, so it lands here too.
    Function,
    /// Plain top-level bindings (a const's initializer renders verbatim).
    Value,
    /// Impl faces: inherent and trait impls, member signatures only.
    Impl,
}

impl Family {
    /// Every family in its fixed section order.
    const ALL: [Self; 8] = [
        Self::Trait,
        Self::Struct,
        Self::Enum,
        Self::Tag,
        Self::Alias,
        Self::Function,
        Self::Value,
        Self::Impl,
    ];

    /// The section heading one family renders under.
    const fn heading(self) -> &'static str {
        match self {
            Self::Trait => "Traits",
            Self::Struct => "Structs",
            Self::Enum => "Enums",
            Self::Tag => "Tags",
            Self::Alias => "Type aliases",
            Self::Function => "Functions",
            Self::Value => "Values",
            Self::Impl => "Impls",
        }
    }
}

/// The toolchain's own reference: the language's ambient core, then the
/// `@std` package's own members. The faces composed into the bundle's
/// core member parse beside the shrunk core's names, so the package
/// section never re-serves the core's own declarations.
fn toolchain_reference() -> Result<String> {
    let mut language = Vec::new();
    let mut std = Vec::new();
    collect_source(
        &mut language,
        ds_stdlib::AMBIENT_FILE,
        ds_stdlib::AMBIENT_CORE_SOURCE,
    )?;
    for (file, source) in [
        (ds_stdlib::JSON_FILE, ds_stdlib::JSON_SOURCE),
        (ds_stdlib::STRINGS_FILE, ds_stdlib::STRINGS_SOURCE),
        (ds_stdlib::BODIED_FILE, ds_stdlib::BODIED_SOURCE),
        (ds_stdlib::CODEC_FILE, ds_stdlib::CODEC_SOURCE),
        (ds_stdlib::DATETIME_FILE, ds_stdlib::DATETIME_SOURCE),
        (ds_stdlib::ERROR_FILE, ds_stdlib::ERROR_SOURCE),
        (ds_stdlib::STD_MEMBERS_FILE, ds_stdlib::STD_MEMBERS_SOURCE),
    ] {
        collect_source(&mut std, file, source)?;
    }
    sort_entries(&mut language);
    sort_entries(&mut std);
    let mut out = String::from(REFERENCE_HEADER);
    out.push('\n');
    render_section(&mut out, "Language (ambient)", &language);
    out.push('\n');
    render_section(&mut out, "@std", &std);
    Ok(out)
}

/// One target's reference: the file itself, or every .ds member below a
/// root in the walk `ds save` collects, merged into one sorted surface.
fn target_reference(target: &Path) -> Result<String> {
    let mut entries = Vec::new();
    for path in member_files(target)? {
        let source =
            fs::read_to_string(&path).with_context(|| format!("reading {}", path.display()))?;
        collect_source(&mut entries, &path.display().to_string(), &source)?;
    }
    sort_entries(&mut entries);
    let mut out = String::new();
    render_section(&mut out, "Surface", &entries);
    Ok(out)
}

/// The target's member files: the file itself, or every .ds below a root
/// in ascending path order — the same walk `ds save` collects.
///
/// # Errors
///
/// A missing target and a root holding no .ds source.
fn member_files(target: &Path) -> Result<Vec<PathBuf>> {
    if target.is_file() {
        return Ok(vec![target.to_path_buf()]);
    }
    anyhow::ensure!(target.exists(), "{} does not exist", target.display());
    let mut members = crate::package::walk_sources(target)?;
    members.sort();
    if members.is_empty() {
        bail!("{} holds no .ds source member", target.display());
    }
    Ok(members)
}

/// The error-code table: every registry code with its own registered
/// description, grouped by class in ascending code order.
fn errors_reference() -> String {
    let mut out = String::from(ERRORS_HEADER);
    for class in [
        ErrorClass::Parse,
        ErrorClass::Type,
        ErrorClass::Linearity,
        ErrorClass::Module,
    ] {
        out.push_str("\n## ");
        out.push_str(class_heading(class));
        out.push_str("\n\n| Code | Description |\n|---|---|\n");
        for code in ErrorCode::ALL.iter().filter(|code| code.class() == class) {
            out.push_str("| `");
            out.push_str(code.as_str());
            out.push_str("` | ");
            out.push_str(&code.doc().trim().replace('|', "\\|"));
            out.push_str(" |\n");
        }
    }
    out
}

/// The table's section heading per error class.
const fn class_heading(class: ErrorClass) -> &'static str {
    match class {
        ErrorClass::Parse => "Parse and syntax (DS1xxx)",
        ErrorClass::Type => "Type system (DS2xxx)",
        ErrorClass::Linearity => "Linearity and ownership (DS3xxx)",
        ErrorClass::Module => "ABI, bytecode, and module (DS4xxx)",
    }
}

/// Parses one member and appends its entries. A parse failure bails with
/// the diagnostics rendered as the run path renders them.
fn collect_source(out: &mut Vec<Entry>, name: &str, source: &str) -> Result<()> {
    let mut files = Files::new();
    let file = files.add_source(name.to_owned(), source);
    let ast = ds_parse::parse(&files, file).map_err(|diags| {
        anyhow::anyhow!(
            "{}",
            diags
                .iter()
                .map(|diag| ds_diag::human(diag, &files))
                .collect::<String>()
        )
    })?;
    collect(out, source, &ast);
    Ok(())
}

/// Every pub face (and every impl) of one parse tree, appended in source
/// order; the caller sorts. Imports and the platform declaration stay
/// out (module plumbing, not surface), and non-pub declarations stay out
/// exactly as the `.dsi` tier's gate keeps them.
fn collect(out: &mut Vec<Entry>, src: &str, ast: &Ast) {
    for item in ast.blocks.iter().flat_map(|block| block.items.iter()) {
        let doc = doc_lines(src, &item.doc);
        let mut face = String::new();
        match &item.kind {
            ItemKind::Impl(decl) => {
                ds_fmt::signature::impl_face(&mut face, src, decl);
                out.push(Entry {
                    family: Family::Impl,
                    label: None,
                    doc,
                    face,
                });
            },
            ItemKind::Import(_) | ItemKind::Platform(_) => {},
            _ if !matches!(item.vis, Some(Vis::Pub(_))) => {},
            kind => {
                ds_fmt::signature::item(&mut face, src, item);
                let (family, label) = classify(kind);
                out.push(Entry {
                    family,
                    label,
                    doc,
                    face,
                });
            },
        }
    }
}

/// One gated item's family and heading label.
fn classify(kind: &ItemKind) -> (Family, Option<String>) {
    match kind {
        ItemKind::Trait(t) => (Family::Trait, Some(t.name.name.clone())),
        ItemKind::Struct(s) => (Family::Struct, Some(s.name.name.clone())),
        ItemKind::Enum(e) => (Family::Enum, Some(e.name.name.clone())),
        ItemKind::Tag(t) => (Family::Tag, Some(t.name.name.clone())),
        ItemKind::TypeAlias(a) => (Family::Alias, Some(a.name.name.clone())),
        ItemKind::Fn(f) | ItemKind::ExternFn(f) => (Family::Function, Some(f.name.name.clone())),
        // A bodied top-level fn is the converted const-arrow binding of
        // one lambda, so it renders and sorts as a function; any other
        // binding is a value.
        ItemKind::Local(local) => match (&local.pat, &local.init) {
            (Pattern::Binding { name, .. }, Expr::Lambda { .. }) => {
                (Family::Function, Some(name.name.clone()))
            },
            (Pattern::Binding { name, .. }, _) => (Family::Value, Some(name.name.clone())),
            _ => (Family::Value, None),
        },
        // The collect gate already routed these.
        ItemKind::Import(_) | ItemKind::Platform(_) | ItemKind::Impl(_) => (Family::Value, None),
    }
}

/// The `///` doc run the parse layer attached to the item, one line per
/// trivia: the bytes minus the `///` marker and one leading space. The
/// attachment rule (a blank line or an ordinary `//` comment cuts the
/// run off) is the parse layer's own, so a declaration's prose in plain
/// `//` stays maintainer notes that never render.
fn doc_lines(src: &str, doc: &[Trivia]) -> Vec<String> {
    doc.iter()
        .map(|t| ds_parse::doc_body(src, t).to_owned())
        .collect()
}

/// One sorted entry list's markdown: a section title, a `###` heading per
/// non-empty family, a `####` heading per labeled entry, the `///` doc
/// run as plain lines, and the face in a `ds` fence. Deterministic by
/// construction: sorted input, fixed family order, no clock.
fn render_section(out: &mut String, title: &str, entries: &[Entry]) {
    out.push_str("## ");
    out.push_str(title);
    out.push('\n');
    for family in Family::ALL {
        let members: Vec<&Entry> = entries
            .iter()
            .filter(|entry| entry.family == family)
            .collect();
        if members.is_empty() {
            continue;
        }
        out.push_str("\n### ");
        out.push_str(family.heading());
        out.push('\n');
        for entry in &members {
            out.push('\n');
            if let Some(label) = &entry.label {
                out.push_str("#### `");
                out.push_str(label);
                out.push_str("`\n\n");
            }
            for line in &entry.doc {
                out.push_str(line);
                out.push('\n');
            }
            if !entry.doc.is_empty() {
                out.push('\n');
            }
            out.push_str("```ds\n");
            out.push_str(&entry.face);
            out.push_str("```\n");
        }
    }
}

/// Sorts into the rendered order: family sections first, then label
/// order inside a family (an unlabeled entry sorts by its face).
fn sort_entries(entries: &mut [Entry]) {
    entries.sort_by(|a, b| {
        a.family
            .cmp(&b.family)
            .then_with(|| a.label.cmp(&b.label))
            .then_with(|| a.face.cmp(&b.face))
    });
}
